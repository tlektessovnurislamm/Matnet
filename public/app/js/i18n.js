/* ---------- helpers ---------- */

/* Default language: saved choice, else browser language (kk → KZ, ru → RU), else KZ. */
function detectLang() {
  var l = (navigator.language || "").toLowerCase();
  return l.indexOf("ru") === 0 ? "ru" : "kz";
}
function getLang() { return Store.get().lang || detectLang(); }

function lookup(key) {
  var o = I18N[getLang()];
  var parts = key.split(".");
  for (var i = 0; i < parts.length; i++) {
    if (o == null) return undefined;
    o = o[parts[i]];
  }
  return o;
}

/* t("common.streak", {n: 5}) → "5 күн қатарынан!" */
function t(key, params) {
  var s = lookup(key);
  if (typeof s !== "string") return key;
  if (params) s = s.replace(/\{(\w+)\}/g, function (m, p) { return params[p] !== undefined ? params[p] : m; });
  return s;
}
/* For arrays (lesson steps, praise lists). */
function tList(key) { var a = lookup(key); return Array.isArray(a) ? a : []; }

/* Fill every [data-i18n] / [data-i18n-aria] element. */
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-i18n")); });
  root.querySelectorAll("[data-i18n-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
  document.documentElement.lang = getLang() === "kz" ? "kk" : "ru";
  var tk = document.body && document.body.getAttribute("data-i18n-title");
  if (tk) document.title = t(tk) + " · " + t("common.title");
}

/* Switch language instantly; pages listen for "langchange" to re-render dynamic parts. */
function setLang(l) {
  Store.get().lang = l;
  Store.save();
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}
